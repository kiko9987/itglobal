# -*- coding: utf-8 -*-
"""숫자로 시작하는 이름('10전투비행단')을 번지 뒤 숫자 + 상호로 쪼개지 않음 (L-04261).

'정조로 409 10전투비행단'이 '409 10 전투비행단'으로 쪼개지던 버그. 같이 정리된 것:
건물 차수('대륭테크노타운12차')가 '12'로 잘려 뒤 층·호가 유실되던 것, 호 범위
('306~309호')의 앞 숫자 조각('30')이 붙던 것.
"""
import sys
sys.path.insert(0, '.')

import pytest
from dashboard.services.lead_helpers import extract_korean_address as X


@pytest.mark.parametrize('text, expected', [
    ('수원시 권선구 정조로 409 10전투비행단 사무실', '수원시 권선구 정조로 409 10전투비행단'),
    ('포천시 이동면 화동로 1747 7862부대', '포천시 이동면 화동로 1747 7862부대'),
    ('은평구 불광로 15 2층 365서울탑치과의원 은평점', '은평구 불광로 15 2층 365서울탑치과의원'),
    ('금천구 가산디지털2로 14 대륭테크노타운12차 905호', '금천구 가산디지털2로 14 대륭테크노타운12차 905호'),
    ('강서구 공항대로 242 열린엠타워 2차 302호', '강서구 공항대로 242 열린엠타워 2차 302호'),
    ('고양 덕양구 꽃마을로 27 엠타워 306~309호', '덕양구 꽃마을로 27 엠타워'),
])
def test_digit_led_names(text, expected):
    assert X(text)[0] == expected


@pytest.mark.parametrize('text, expected', [
    ('강남구 테헤란로 152 12월말 설치', '강남구 테헤란로 152'),   # 날짜 표현 미부착
    ('강남구 테헤란로 152 30평정도', '강남구 테헤란로 152'),      # 면적 표현 미부착
    ('강남구 테헤란로 152 3층', '강남구 테헤란로 152 3층'),
    ('은평구 갈현로3나길 23 102동 501호', '은평구 갈현로3나길 23 102동 501호'),
    ('영등포구 국제금융로2길 36 8~9층', '영등포구 국제금융로2길 36'),  # L-04115 기존 동작
])
def test_no_regression(text, expected):
    assert X(text)[0] == expected


if __name__ == '__main__':
    sys.exit(pytest.main([__file__, '-v']))
