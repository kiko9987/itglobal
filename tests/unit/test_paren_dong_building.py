# -*- coding: utf-8 -*-
"""괄호 '(법정동 건물명)' 정리 — 법정동 제거·건물명 unwrap (L-03702·L-03771).

매니저가 '(갈현동 벧엘)'·'(고잔동, Win-Win프라자)' 처럼 법정동+건물을 괄호로 적으면 법정동
빼고 건물명만 밖으로 (콤마형/무-콤마 둘 다). 번지형('(걸포동 172-1)')은 건물부가 숫자로
시작해 미매치(보존), 동 단독은 별도 제거 규칙. 순수함수 _post_normalize_display.
"""
import sys
sys.path.insert(0, '.')

import pytest
from dashboard.services.address_resolver import _post_normalize_display as P


@pytest.mark.parametrize('addr, expected', [
    # 무-콤마 (법정동 건물) → unwrap
    ('은평구 통일로 875 (갈현동 벧엘) 1층 중앙약국', '은평구 통일로 875 벧엘 1층 중앙약국'),
    ('수원 팔달로 1 (매탄동 삼성전자) 2층', '수원 팔달로 1 삼성전자 2층'),
    ('서초구 강남대로 1 (서초동 우성빌딩)', '서초구 강남대로 1 우성빌딩'),
    # 동N가·로N가 법정동 (L-03707)
    ('성동구 아차산로 103 (성수동2가 영동테크노타워) 10층 1004호',
     '성동구 아차산로 103 영동테크노타워 10층 1004호'),
    ('중구 세종대로 1 (을지로3가 삼성빌딩) 5층', '중구 세종대로 1 삼성빌딩 5층'),
    # 중첩 괄호 (법인 (주)/㈜) — 내부 괄호 보존 unwrap (L-03716)
    ('시흥 공단1대로195번길 38 (정왕동 (주)삼인)', '시흥 공단1대로195번길 38 (주)삼인'),
    ('부천 부천로 1 (심곡동 ㈜대성) 2층', '부천 부천로 1 ㈜대성 2층'),
    # 콤마형 '(법정동, 건물명)' 도 unwrap (L-03771)
    ('안산 단원구 광덕4로 260 (고잔동, Win-Win프라자) 4층',
     '안산 단원구 광덕4로 260 Win-Win프라자 4층'),
    ('강남구 테헤란로 152 (역삼동, 강남빌딩) 3층', '강남구 테헤란로 152 강남빌딩 3층'),
])
def test_no_comma_dong_building_unwrapped(addr, expected):
    assert P(addr) == expected


@pytest.mark.parametrize('addr', [
    '김포 사우중로 1 (걸포동 172-1)',   # 번지형 — 건물부 숫자 시작, 미매치(보존)
    '서초구 방배로 20 (서초대로 삼성빌딩) 3층',  # 도로명(숫자+가 없음) — 법정동 오인 방지, 보존
    '평택 산단로 5 (관리동)',            # 건물 구역동 — L-03779 negative lookahead 제외(보존)
    '서초구 강남대로 1 우성빌딩 (서초동)',  # 법정동 단독이나 번지 직후 아님 — L-03779 미매치(보존)
])
def test_preserved(addr):
    assert P(addr) == addr


@pytest.mark.parametrize('addr, expected', [
    # 법정동 단독 괄호 '(법정동)' 이 **번지(숫자) 직후** 오면 제거 (2026-08-25 L-03779):
    #   다음(카카오) 우편번호 위젯 '도로명 번지 (법정동)' 시그니처 → 당근·전화(괄호 없음)와
    #   표기 통일. (2026-08-18 작성 당시엔 미매치·보존이었으나 L-03779 로 의도 변경됨.)
    ('김포 사우중로 1 (걸포동)', '김포 사우중로 1'),
    ('인천 원창로 16-8 (원창동)', '인천 원창로 16-8'),
    ('평택 산단로 5 (칠괴동) 관리동', '평택 산단로 5 관리동'),  # 법정동 제거·구역동 보존
])
def test_standalone_dong_after_bunji_removed(addr, expected):
    assert P(addr) == expected


if __name__ == '__main__':
    sys.exit(pytest.main([__file__, '-v']))
